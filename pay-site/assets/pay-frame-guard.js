/* Защита от clickjacking без серверных заголовков.

   Правильный способ - заголовки frame-ancestors и X-Frame-Options, но на этом
   хостинге статику отдаёт nginx, а он .htaccess не читает: заголовки не
   применяются (проверено 01.09.2026, на живом поддомене их нет ни одного).
   Тегом <meta> frame-ancestors задать нельзя - директива работает только в
   заголовке.

   Поэтому старый приём: если страница оказалась внутри фрейма, выбиваемся из
   него. Атака, от которой это спасает: наш кабинет грузят в прозрачный фрейм,
   сверху кладут свою страницу, и человек нажимает «Оплатить», думая, что жмёт
   что-то другое.

   Как только заголовки появятся на сервере, этот файл можно удалить - но не
   раньше: пока его нет, страница защищена только им. */

(function () {
  'use strict';
  try {
    if (window.top === window.self) return;
  } catch (e) {
    // Доступ к window.top бросает исключение, если фрейм с чужого домена -
    // а это как раз тот случай, от которого защищаемся.
  }
  // Показывать что-либо внутри фрейма нельзя даже на мгновение: снимок экрана
  // чужой странице тоже не нужен.
  document.documentElement.style.display = 'none';
  try {
    window.top.location = window.self.location.href;
  } catch (e) {
    // Сменить адрес верхнего окна не дали - тогда просто уходим сами.
    window.self.location = 'https://kubysh.com/';
  }
})();
